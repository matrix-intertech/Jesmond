/**
 * Returns human-readable country name from ISO-3166-1 alpha-2 code or name.
 */
export function getCountryName(codeOrName?: string | null): string {
  if (!codeOrName) return '';
  const trimmed = codeOrName.trim();
  const found = COUNTRIES.find(
    (c) =>
      c.code.toUpperCase() === trimmed.toUpperCase() ||
      c.name.toLowerCase() === trimmed.toLowerCase(),
  );
  return found ? found.name : trimmed;
}

